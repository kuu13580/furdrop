-- 写真の DL 期限を 30日 → 365日 に延長する (R13/X11)。
--
-- これまで expires_at はどこからも書き込まれず常に NULL で、Cron が
-- COALESCE(expires_at, created_at + 30日) で判定していた = 実質「受信日から一律30日」。
-- 定数を 365日 に変えるだけでも既存写真に遡及はするが、裏返しに
-- 将来値を短くしたとき過去分が一斉に物理削除される。
--
-- ここで実値を焼き込んで photos.expires_at を唯一の真実にし、以降の定数変更は
-- 新しく届く写真にだけ効くようにする。遡及の範囲もこの migration の履歴として残る。
-- updated_at は触らない。これは運用側の一括操作であって個々のレコードの更新ではなく、
-- 全行を同じ時刻で塗り潰すと「そのレコードが最後にいつ変わったか」の手がかりを失うため。
UPDATE photos
   SET expires_at = created_at + 31536000  -- 365日
 WHERE expires_at IS NULL;
